using System;

/// <summary>Explicit account authority injected by the existing GameData owner. No default SDK or fake fallback.</summary>
public interface IPopupStoreAccountPhaseBridge
{
    PopupStoreAdmissionHost AdmissionHost { get; }
    bool IsReady { get; }
    string Status { get; }
    void PrepareResult(PopupStorePhaseSession session, PopupStorePhaseResult result,
        Action<PopupStoreAccountClaimResult> completed);
    void FinalizeAndClaim(PopupStorePhaseSession session, PopupStorePhaseResult result,
        Action<PopupStoreAccountClaimResult> completed);
}

/// <summary>Advances only the account request timeout/reconciliation observer, never gameplay time.</summary>
public interface IPopupStoreAccountProgress
{
    void ObserveElapsed(double elapsed);
}

public enum PopupStoreAccountClaimState { Confirmed, Pending, Retryable, Rejected }

/// <summary>A response for the original saved business, never an amount generated by the review presentation.</summary>
public sealed class PopupStoreAccountClaimResult
{
    public PopupStoreAccountClaimState State { get; }
    public string BusinessSessionId { get; }
    public int Diamonds { get; }
    public string Message { get; }
    public PopupStoreAccountClaimResult(PopupStoreAccountClaimState state, string businessSessionId,
        int diamonds, string message)
    { State = state; BusinessSessionId = businessSessionId; Diamonds = diamonds; Message = message; }
}

public interface IPopupStoreAccountRewardRecovery
{
    PopupStoreAccountRecoverySnapshot Recovery { get; }
    void ClaimRecovery(Action<PopupStoreAccountClaimResult> completed);
}

/// <summary>Stored account result only; never recreates or advances a completed phase session.</summary>
public sealed class PopupStoreAccountRecoverySnapshot
{
    public string SessionId { get; }
    public int Score { get; }
    public PopupStoreGradeTier Grade { get; }
    public bool EligibleReward { get; }
    public int Diamonds { get; }
    public bool IsInterrupted { get; }
    public PopupStoreAccountRecoverySnapshot(string sessionId, int score, PopupStoreGradeTier grade,
        bool eligibleReward, int diamonds, bool isInterrupted)
    { SessionId = sessionId; Score = score; Grade = grade; EligibleReward = eligibleReward;
        Diamonds = diamonds; IsInterrupted = isInterrupted; }
}
